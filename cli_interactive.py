import sys
from typing import Optional
from main import ConsultationAgent


def interactive_mode():
    """
    交互式对话模式
    用户可以连续输入问题，Agent 实时响应
    🔄【改进】支持多轮对话的状态保持
    """
    print("\n" + "="*70)
    print("🏥 智能预问诊与数据枢纽 Agent - 交互式模式")
    print("="*70)
    print("\n💡 使用方法:")
    print("  - 输入您的症状或需求（支持中文）")
    print("  - 输入 'help' 查看帮助")
    print("  - 输入 'exit' 或 'quit' 退出程序")
    print("  - 输入 'examples' 查看示例")
    print("="*70 + "\n")
    
    try:
        # 初始化 Agent
        print("🔄 正在初始化 Agent...")
        agent = ConsultationAgent(model_name="qwen-max-latest")
        print("✅ Agent 已就绪！\n")
        
    except Exception as e:
        print(f"❌ 初始化失败: {e}")
        print("请确保已配置 API Key（见 README.md）")
        return
    
    turn_count = 0
    # 🔄【新增】保存状态用于跨轮次处理
    persistent_state = None
    
    while True:
        try:
            # 获取用户输入
            if turn_count == 0:
                prompt = "👤 请描述您的症状或需求: "
            else:
                prompt = "👤 继续输入: "
            
            user_input = input(prompt).strip()
            
            # 处理特殊命令
            if not user_input:
                print("⚠️  请输入内容\n")
                continue
            
            if user_input.lower() in ['exit', 'quit', 'q']:
                print("\n👋 谢谢使用，再见！\n")
                break
            
            if user_input.lower() == 'help':
                print_help()
                continue
            
            if user_input.lower() == 'examples':
                print_examples()
                continue
            
            # 执行咨询
            turn_count += 1
            print("\n🤖 Agent 正在处理您的问题...\n")
            
            response, new_state = agent.run_consultation(
                user_query=user_input,
                turn_count=turn_count,
                verbose=False,
                previous_state=persistent_state
            )
            
            # 🔄【新增】保存状态以供下一轮使用
            persistent_state = new_state
            
            print("─" * 70)
            print(f"🤖 Agent 的回复 (第 {turn_count} 轮):\n")
            print(response)
            print("─" * 70 + "\n")
            
            # 检查对话是否结束
            if new_state.is_conversation_ended:
                print("💡 咨询已完成。如有新问题，请重新启动程序。\n")
                break
            
        except KeyboardInterrupt:
            print("\n\n👋 程序已中止")
            break
        except Exception as e:
            print(f"\n❌ 出现错误: {e}")
            print("   请重新输入或使用 'exit' 退出\n")


